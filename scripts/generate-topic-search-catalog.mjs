#!/usr/bin/env node
/**
 * Copies only the topic wording out of every `common.json` so the search
 * needn't bundle all locales. Rerun after changing `registration.topic.catalog`.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const i18nDir = join(root, 'src/resources/i18n');
const outFile = join(
	root,
	'src/components/registration/topicSearch/topicSearchCatalog.generated.ts'
);

export const buildTopicSearchCatalog = () => {
	const topics = {};

	readdirSync(i18nDir, { withFileTypes: true })
		.filter((entry) => entry.isDirectory() && !entry.name.includes('@'))
		.map((entry) => entry.name)
		.sort()
		.forEach((lang) => {
			const common = JSON.parse(
				readFileSync(join(i18nDir, lang, 'common.json'), 'utf8')
			);
			const topic = common?.registration?.topic ?? {};

			Object.entries(topic.catalog ?? {}).forEach(([key, copy]) => {
				if (!copy?.title) return;
				topics[key] ??= {};
				topics[key][lang] = {
					title: copy.title,
					description: copy.description ?? ''
				};
			});
		});

	const sortKeys = (object) =>
		Object.fromEntries(
			Object.keys(object)
				.sort()
				.map((key) => [key, object[key]])
		);

	return { topics: sortKeys(topics) };
};

export const renderTopicSearchCatalog = (catalog) =>
	`/* eslint-disable */
// Generated by scripts/generate-topic-search-catalog.mjs — do not edit.
// Source: registration.topic.catalog in src/resources/i18n/*/common.json

export type TopicSearchCatalogCopy = { title: string; description: string };

export const topicSearchCatalog: {
	topics: Record<string, Record<string, TopicSearchCatalogCopy>>;
} = ${JSON.stringify(catalog, null, '\t')};
`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(outFile, renderTopicSearchCatalog(buildTopicSearchCatalog()));
	console.log(`wrote ${outFile}`);
}
